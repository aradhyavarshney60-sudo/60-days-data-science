recent_customers = set(
    df.loc[
        df[date_col] >= recent_start,
        customer_col
    ].unique()
)

# Customers active before the latest 30-day period
previous_customers = set(
    df.loc[
        df[date_col] < recent_start,
        customer_col
    ].unique()
)

retained_customers = (
    recent_customers.intersection(previous_customers)
)

if len(previous_customers) > 0:

    retention_rate = (
        len(retained_customers)
        / len(previous_customers)
        * 100
    )

else:

    retention_rate = 0


