def find_column(columns, keywords):
    """
    Find a column based on common keyword patterns.
    """
    for keyword in keywords:
        for col in columns:
            if keyword in col.lower():
                return col
    return None


def prepare_data(df):
    """
    Automatically detect important customer columns.
    """

    columns = list(df.columns)

    customer_col = find_column(
        columns,
        [
            "customer_id",
            "customerid",
            "customer",
            "client_id",
            "client",
            "user_id",
            "userid"
        ]
    )

    date_col = find_column(
        columns,
        [
            "purchase_date",
            "transaction_date",
            "order_date",
            "date",
            "timestamp",
            "created_at"
        ]
    )

    revenue_col = find_column(
        columns,
        [
            "revenue",
            "amount",
            "sales",
            "purchase_amount",
            "order_value",
            "total_amount",
            "price",
            "spend"
        ]
    )

    return customer_col, date_col, revenue_col


def calculate_clv(df, customer_col, revenue_col):
    """
    Calculate simplified historical Customer Lifetime Value.

    CLV here represents historical customer revenue:
        CLV = Total Revenue generated by customer
    """

    customer_summary = (
        df.groupby(customer_col)
        .agg(
            Total_Revenue=(revenue_col, "sum"),
            Number_of_Transactions=(revenue_col, "count"),
            Average_Transaction_Value=(revenue_col, "mean")
        )
        .reset_index()
    )

    customer_summary["CLV"] = customer_summary["Total_Revenue"]

    return customer_summary


