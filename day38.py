customer_summary = (
    df.groupby(customer_col)
    .agg(
        First_Purchase=(date_col, "min"),
        Last_Purchase=(date_col, "max"),
        Total_Revenue=(revenue_col, "sum"),
        Number_of_Transactions=(revenue_col, "count"),
        Average_Transaction_Value=(revenue_col, "mean")
    )
    .reset_index()
)

customer_summary["Customer_Lifetime_Days"] = (
    customer_summary["Last_Purchase"]
    - customer_summary["First_Purchase"]
).dt.days

customer_summary["Customer_Lifetime_Days"] = (
    customer_summary["Customer_Lifetime_Days"].clip(lower=1)
)

# Historical CLV
customer_summary["CLV"] = customer_summary["Total_Revenue"]


# ============================================================
# RETENTION ANALYSIS
# ============================================================

st.header("📈 Customer Retention Analysis")

